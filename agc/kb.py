"""The knowledge base (`.claude/skills/agc-notes/kb/`): what was measured on this device, as entries
agents read and search.

- `OPTIMIZATIONS.md` (curated): every optimization, when it applies, how to apply it, what it measured.
- `PATTERNS.md` (curated): the short decision guide.
- `RECIPES.md`, `INDEX.md` (generated by `scripts/kb.py`): every verified result with its recipe; every entry.
- `<kernel>.md`: entries written from the agent sessions' reports on that kernel.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
KB = REPO / ".claude" / "skills" / "agc-notes" / "kb"
CURATED = ("README.md", "PATTERNS.md", "OPTIMIZATIONS.md", "RECIPES.md", "INDEX.md")


def entries() -> list[dict]:
    out = []
    for f in sorted(KB.glob("*.md")):
        if f.name in CURATED:
            continue
        for e in f.read_text().split("\n## ")[1:]:
            title = e.split("\n")[0].strip()
            get = lambda k: (re.search(rf"\*\*{k}:\*\* (.*)", e) or [None, ""])[1]
            out.append({"kernel": f.stem, "title": title, "verdict": get("Verdict"), "applies": get("Applies when"),
                        "how": get("How"), "measured": get("Measured")})
    return out


def catalog() -> list[dict]:
    """The curated optimizations (`OPTIMIZATIONS.md`): one entry per `### ` heading."""
    p = KB / "OPTIMIZATIONS.md"
    if not p.exists():
        return []
    out = []
    for e in p.read_text().split("\n### ")[1:]:
        title, _, body = e.partition("\n")
        body = body.split("\n## ")[0]
        get = lambda k: (re.search(rf"\*\*{k}:\*\* ((?:.|\n(?!- \*\*))*)", body) or [None, ""])[1]
        out.append({"kernel": "catalog", "title": title.strip(), "verdict": " ".join(get("Verdict").split()),
                    "applies": " ".join(get("Applies when").split()), "how": " ".join(get("How").split()),
                    "measured": " ".join(get("Measured").split())})
    return out


def search(query: str, limit: int = 8) -> list[dict]:
    """Entries of the knowledge base ranked by how many of the query's words they contain (title and
    `applies when` count double)."""
    words = [w for w in re.findall(r"[a-z0-9_]+", query.lower()) if len(w) > 2]
    scored = []
    for e in catalog() + entries():
        head, body = f"{e['title']} {e['applies']} {e['kernel']}".lower(), f"{e['how']} {e['measured']}".lower()
        s = sum(2 * (w in head) + (w in body) for w in words)
        if s >= 2:                                       # ties go to wins and to the curated catalog
            s += 0.5 * e["verdict"].lower().startswith("pays") + 3 * (e["kernel"] == "catalog")
        if s >= 2:
            scored.append((s, e))
    return [e for _, e in sorted(scored, key=lambda x: -x[0])[:limit]]


# ---- the generated files -----------------------------------------------------
BASE = REPO / "tests" / "baselines"
SESSIONS = REPO / "bench" / "llm" / "sessions"
HEAD = "<!-- generated by scripts/kb.py from the records; do not edit -->\n"


def _load(name: str) -> dict:
    p = BASE / name
    return json.loads(p.read_text()) if p.exists() else {}


def _ci(v) -> str:
    return f"{v[0]:.3f} to {v[1]:.3f}" if v else ""


def _cell(text: str, n: int = 420) -> str:
    text = " ".join(str(text).split()).replace("|", "/")
    if len(text) <= n:
        return text
    cut = text[:n]
    return cut[:max(cut.rfind(". "), cut.rfind("; "), n // 2) + 1].rstrip() + " …"


def _launch(l: dict | None) -> str:
    if not l:
        return ""
    parts = [f"grid {l['grid']}", f"block {l['block']}"] + ([f"lds {l['lds']}"] if l.get("lds") else []) + \
            ([f"args {[a['value'] for a in l['args']]}"] if l.get("args") else [])
    return _cell(", ".join(parts).replace("'", ""), 200)


def recipes() -> str:
    L = [HEAD, "# Recipes: every verified result and how to reproduce it", "",
         "Speedups are paired timings with their 95 % CI, after the static checks and the full battery. LLM-benchmark",
         "results are over the strongest amdclang build of the kernel; corpus results are over `amdclang -O3`.",
         "`agc replay KERNEL` replays a session recipe; `apply`, `generate` and `relaunch` are session tools.", ""]
    rows = []
    for d in sorted(SESSIONS.glob("*")):
        if (d / "recipe.json").exists():
            r = json.loads((d / "recipe.json").read_text())
            rows.append((r["verified"]["speedup"], d.name, r))
    L += ["## Agent-session recipes (LLM benchmark)", "",
          "The code is `bench/llm/sessions/<kernel>/best.s`, the launch and the verdict `recipe.json`, the per-kernel analysis",
          "`docs/kernels/<kernel>.md` where one exists.", "",
          "| kernel | speedup (95% CI) | bit-identical to the original | steps | launch | what it does |", "|---|---|---|---|---|---|"]
    eq = _load("llm-equivalence-gfx950.json").get("kernels", {})
    for sp, n, r in sorted(rows, key=lambda x: -x[0]):
        e = (eq.get(n) or {}).get("session recipe") or {}
        bit = "" if not e else "yes" if e.get("bit_identical") else "within tolerance"
        steps = " + ".join(x for x in r["path"] if x != "adopt")
        L.append(f"| `{n}` | **{sp:.3f}** ({_ci(r['verified']['speedup_ci95'])}) | {bit} | {steps} | {_launch(r.get('launch'))} | {_cell(r.get('summary', ''))} |")
    pol = _load("llm-gfx950.json").get("kernels", {})
    L += ["", "## Default-policy results (LLM benchmark)", "", "One pass on the strongest amdclang build, no agent: `apply(\"baseline\", pass, params)`.", "",
          "| kernel | pass | speedup (95% CI) |", "|---|---|---|"]
    for n, k in pol.items():
        if not k["fallback"]:
            c = k["chosen"]
            L.append(f"| `{n}` | `{c['how']}` | {c['speedup']:.3f} ({_ci(c.get('ci95'))}) |")
    cor = _load("policy-gfx950.json").get("kernels", {})
    L += ["", "## Default-policy results (corpus, `tests/kernels`)", "", "| kernel | pass or template | speedup (95% CI) |", "|---|---|---|"]
    for n, k in cor.items():
        c = k["chosen"]
        if not k["fallback"] and c.get("speedup"):
            L.append(f"| `{n}` | `{c['how']}` | {c['speedup']:.3f} ({_ci(c.get('ci95'))}) |")
    L.append("")
    L.append("No verified win (fallback): " + ", ".join(f"`{n}`" for n, k in cor.items() if k["fallback"]) + ".")
    gen = _load("generated-gfx950.json").get("kernels", {})
    L += ["", "## Generator templates (tensor program to machine IR)", "", "`generate(template, params)` on a manifest with a `program`.", "",
          "| kernel | template | best parameters | speedup (95% CI) | instructions |", "|---|---|---|---|---|"]
    for n, k in gen.items():
        bst = k["best"]
        if bst and bst.get("speedup"):
            L.append(f"| `{n}` | `{k['template']}` | {bst['params']} | {bst['speedup']:.3f} ({_ci(bst.get('ci95'))}) | {bst.get('instructions', '')} |")
    gm = _load("gemm-gfx950.json")
    if gm:
        L += ["", "## GEMM on MFMA", "", f"{gm['operation']}; template `gemm_mfma`.", "",
              "| shape | best parameters | TFLOP/s | over amdclang | hipBLASLt is faster by |", "|---|---|---|---|---|"]
        for name, s in gm["shapes"].items():
            bst = s["best"]
            L.append(f"| {name} ({s['M']} x {s['N']} x {s['K']}) | {bst['params']} | {bst['tflops']} | {bst['vs_amdclang']} | {bst['hipblaslt_ratio']:.2f}x |")
    fp = _load("gemm-fp8-gfx950.json")
    if fp:
        L += ["", "## GEMM on the FP8 MFMAs", "", f"{fp['operation']}; template `gemm_mfma` on `tests/kernels/gemm_fp8`.", "",
              "| shape | best parameters | TFLOP/s | over amdclang | hipBLASLt (FP8) is faster by |", "|---|---|---|---|---|"]
        for name, s in fp["shapes"].items():
            bst = s["best"]
            L.append(f"| {name} ({s['M']} x {s['N']} x {s['K']}) | {bst['params']} | {bst['tflops']} | {bst['vs_amdclang']} | {bst['hipblaslt_ratio']:.2f}x |")
    wins = sorted((REPO / "tests" / "mir" / "wins").glob("*.s"))
    if wins:
        L += ["", "## Hand-written machine-IR wins (corpus)", "",
              "Replayable traces next to each file (`<name>.trace.json`).", ""]
        L += [f"- `tests/mir/wins/{w.name}`" for w in wins]
    return "\n".join(L) + "\n"


def index() -> str:
    es = entries()
    L = [HEAD, "# Index of the per-kernel entries", "",
         f"{len(es)} entries in {len({e['kernel'] for e in es})} kernel files, by verdict. The numbers in the entries are the sessions' own",
         "measurements; the harness-verified results are in `RECIPES.md`.", ""]
    for key, head in (("pays", "Pays"), ("parity", "Parity"), ("loses", "Loses")):
        sel = [e for e in es if e["verdict"].lower().startswith(key)]
        L += [f"## {head} ({len(sel)})", "", "| kernel | optimization | applies when |", "|---|---|---|"]
        L += [f"| [`{e['kernel']}`]({e['kernel']}.md) | {_cell(e['title'], 160)} | {_cell(e['applies'], 220)} |" for e in sel]
        L.append("")
    rest = [e for e in es if not e["verdict"].lower().startswith(("pays", "parity", "loses"))]
    if rest:
        L += [f"## Other ({len(rest)})", ""] + [f"- [`{e['kernel']}`]({e['kernel']}.md): {_cell(e['title'], 160)} ({_cell(e['verdict'], 60)})" for e in rest]
    return "\n".join(L).rstrip() + "\n"


def generated() -> dict[str, str]:
    return {"RECIPES.md": recipes(), "INDEX.md": index()}


def write() -> dict[str, int]:
    out = {}
    for n, t in generated().items():
        (KB / n).write_text(t)
        out[n] = len(t.splitlines())
    return out
