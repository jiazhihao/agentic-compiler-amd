#!/usr/bin/env python
"""Write docs/report.md from the recorded measurements (tests/baselines/*.json, tests/mir/wins)."""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from agc import corpus

ROOT = corpus.CORPUS_DIR.parent.parent
B = corpus.BASELINES.parent


def main() -> int:
    base = json.loads((B / "amdclang-gfx950.json").read_text())
    pol = json.loads((B / "policy-gfx950.json").read_text())
    genr = json.loads((B / "generated-gfx950.json").read_text())
    gemm = json.loads((B / "gemm-gfx950.json").read_text())
    wins = {}
    for t in sorted((ROOT / "tests" / "mir" / "wins").glob("*.trace.json")):
        steps = json.loads(t.read_text())
        wins[t.name.split("_unroll")[0].split("_bulk")[0]] = (t.name.replace(".trace.json", ".s"), steps[-1])
    L = ["# Results", "",
         "Generated by `scripts/report.py` from the records in `tests/baselines/` and `tests/mir/wins/`. "
         f"Device: AMD Instinct MI355X (gfx950), ROCm {base['toolchain']['rocm']}. Baseline: `amdclang -O3` on the HIP "
         f"version of each kernel. Protocol `{base['protocol']}`: both code objects alternate in one process, the "
         "statistic is the median of the paired ratio with a 95 % bootstrap interval, and a result is a win only when "
         "the whole interval is above 1.01. Every agc result passed the full battery (hidden seeds, shape variants) "
         "before it was timed.", "",
         "## Per kernel", "",
         "`policy` is what `agc optimize` produces unattended; `agent` is the best state of an agent session through "
         "the MCP server, where one exists. Bit-identical means the same floating-point operations in the same order "
         "as amdclang's code; otherwise the result meets the manifest's tolerance.", "",
         "| Kernel | amdclang ms | Policy: how | Policy speedup (95 % CI) | Bit-identical | Agent session |",
         "|---|---|---|---|---|---|"]
    speed = []
    for n in sorted(pol["kernels"]):
        k, c = pol["kernels"][n], pol["kernels"][n]["chosen"]
        ms = base["kernels"].get(n, {}).get("median_ms")
        if k["fallback"]:
            sp, how = "1.0 (fallback)", "amdclang's build"
            speed.append(1.0)
        elif c.get("ci95"):
            sp, how = f"{c['speedup']:.2f} ({c['ci95'][0]:.2f} to {c['ci95'][1]:.2f})", f"{c['path']}: {c['how']}"
            speed.append(c["speedup"])
        else:
            sp, how = f"no baseline ({c['ms']:.3f} ms)", f"{c['path']}: {c['how']}"
        agent = ""
        if n in wins:
            f, last = wins[n]
            b = last["bench"]
            agent = f"{b['speedup']:.2f} ({b['speedup_ci95'][0]:.2f} to {b['speedup_ci95'][1]:.2f}), `{f}`"
            if k["fallback"]:
                speed[-1] = max(speed[-1], 1.0)
        L.append(f"| `{n}` | {ms if ms else '-'} | {how} | {sp} | {'yes' if c['bit_identical'] else 'no'} | {agent} |")
    s = pol["summary"]
    gm = lambda xs: math.exp(sum(map(math.log, xs)) / len(xs))
    best = []
    for n, k in pol["kernels"].items():
        c = k["chosen"]
        if c.get("speedup") is None:
            continue
        v = c["speedup"]
        if n in wins:
            v = max(v, wins[n][1]["bench"]["speedup"])
        best.append((n, v))
    no_mfma = [v for n, v in best if n != "gemm_bf16"]
    L += ["", f"Policy alone: {s['wins']} wins and {s['fallbacks']} fallbacks over {s['with_baseline']} kernels with a baseline; "
          f"geomean {s['geomean_without_mfma_gemm']} without the MFMA GEMM (fallbacks count as 1.0), {s['geomean']} with it. "
          f"Taking the better of policy and agent session per kernel: geomean {gm(no_mfma):.3f} without the MFMA GEMM, "
          f"{gm([v for _, v in best]):.3f} with it.", "",
          "## GEMM against hipBLASLt", "",
          f"{gemm['operation']}. amdclang emits no MFMA for the HIP kernel, so the meaningful comparison is the library.", "",
          "| Shape | amdclang ms | agc ms | hipBLASLt ms | agc vs amdclang | agc time / hipBLASLt time | agc TFLOPS |", "|---|---|---|---|---|---|---|"]
    for n, sh in gemm["shapes"].items():
        b = sh["best"]
        L.append(f"| {sh['M']} x {sh['N']} x {sh['K']} | {sh['amdclang_ms']:.2f} | {b['ms']:.4f} | {sh['hipblaslt_ms']:.4f} | "
                 f"{b['vs_amdclang']:.0f}x | {b['hipblaslt_ratio']:.2f} | {b['tflops']:.0f} |")
    ratios = [sh["best"]["hipblaslt_ratio"] for sh in gemm["shapes"].values()]
    L += ["", f"agc takes {min(ratios):.1f}x to {max(ratios):.1f}x hipBLASLt's time. The kernel is bound by operand-load throughput (7 to 8 TB/s in "
          "every variant); the next factor needs operands shared between waves through LDS (issue #23). The roadmap's "
          "target of 1.5x was not met.", "",
          "## Controls", "",
          "A/A control (the same code object against itself) from the recording run of each baseline:", "",
          "| Kernel | A/A ratio | 95 % CI |", "|---|---|---|"]
    for n, k in sorted(base["kernels"].items()):
        L.append(f"| `{n}` | {k['aa_speedup']:.4f} | {k['aa_ci95'][0]:.4f} to {k['aa_ci95'][1]:.4f} |")
    aa = [abs(k["aa_speedup"] - 1) for k in base["kernels"].values()]
    L += ["", f"Largest deviation from 1.0: {max(aa) * 100:.2f} %.", "",
          "## What did not work", "",
          "| Attempt | Result |", "|---|---|"]
    for n, k in sorted(pol["kernels"].items()):
        for r in k["candidates"]:
            if r["outcome"] in ("loss", "parity"):
                L.append(f"| `{n}`: {r['how']} | {r['outcome']}, {r['speedup']:.3f} ({r['ci95'][0]:.3f} to {r['ci95'][1]:.3f}) |")
    L += ["| `axpy`: all arguments in one scalar load (agent edit) | parity, 0.9995 (0.993 to 1.004) |",
          "| `matvec`: first unroll attempt with `v[5:8]` (agent edit) | rejected by the static check (tuple alignment) |",
          "| `transpose`, `gemm_tiled` | no candidate: no counted load loop, no template; amdclang's build is shipped |",
          f"| MFMA GEMM within 1.5x of hipBLASLt | not reached ({min(ratios):.1f}x at best) |", "",
          ]
    llm = B / "llm-gfx950.json"
    if llm.exists():
        import importlib.util
        spec = importlib.util.spec_from_file_location("llmbench", Path(__file__).with_name("llmbench.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        L += ["## LLM-kernel benchmark (default policy)", "",
              "Kernels from FlashInfer, vLLM, rocBLAS and MIOpen, and ports of attention, MLA, KDA and MoE kernels "
              "(`bench/llm/README.md`). This is the default policy only, measured against each kernel's baseline: the "
              "strongest amdclang build found for it (next section), not merely -O3 on the source as shipped.", "",
              mod.table(json.loads(llm.read_text())), ""]
        spec = importlib.util.spec_from_file_location("sessions", Path(__file__).with_name("sessions.py"))
        ses = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(ses)
        if ses.STRONG.exists():
            L += ["## LLM-kernel benchmark (agent sessions)", "",
                  "One agent session per kernel through the harness (`agc agent`); each number is the harness's own "
                  "verification of the recorded recipe (static check, full battery, the lower of two 240-pair timings) "
                  "against the strongest amdclang build.", "", ses.table(), ""]
    L += ["## Reproduce", "",
          "```", "make test                       # CPU tests, then GPU tests through the executor",
          "make baseline                   # amdclang baselines", ".venv/bin/python scripts/policy.py     # the default policy on every manifest",
          ".venv/bin/python scripts/generated.py  # every generated variant", ".venv/bin/python scripts/gemm.py       # GEMM against amdclang and hipBLASLt",
          ".venv/bin/python scripts/strong_baseline.py run  # the strongest amdclang build per LLM kernel (the baseline)",
          ".venv/bin/python scripts/llmbench.py   # the LLM-kernel benchmark",
          ".venv/bin/python scripts/report.py     # this file", "```", ""]
    (ROOT / "docs" / "report.md").write_text("\n".join(L))
    print(f"docs/report.md: {len(L)} lines; best-of geomean without MFMA GEMM {gm(no_mfma):.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
